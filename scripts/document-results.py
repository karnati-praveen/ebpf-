#!/usr/bin/env python3
"""Describe every results folder using retained provenance and run metadata.

Generated guides are local documentation, not additional source experiment data.
Existing READMEs and measured files are never overwritten.
"""
import csv
from datetime import datetime
import hashlib
import json
import os
from pathlib import Path
from urllib.parse import quote
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
MARKER = "<!-- Generated by scripts/document-results.py; local guide, not source experiment data. -->"


def link(folder, target, label=None):
    target = Path(target)
    if not target.is_absolute():
        target = ROOT / target
    return f"[{label or target.name}]({quote(os.path.relpath(target, folder), safe='/.-')})"


def role(experiment, relative):
    parts = Path(relative).parts
    if "archive" in parts:
        return "Archived pilot or interrupted run; excluded from the completed main matrix."
    if experiment == "azure-vm-2026-10-04" and "replay" in parts:
        return "Analytical replay of recorded candidates; these rows are not new live inference trials."
    if "provenance" in parts:
        return "Supporting source snapshots, launch scripts, settings or process logs; not an outcome dataset."
    if "decision-results" in parts:
        return "Deterministic cost-model and gate-policy sweep; predicted quantities, not measured inference."
    if "calibration-results" in parts:
        return "Synthetic loopback RPC instrumentation calibration; compare instrumented and control measurements."
    if "queue-results" in parts:
        return "Synthetic sleep-based worker queueing measurements on loopback; no real model or physical network."
    if "fifo-baseline" in parts:
        return "Synthetic replica-only follow-up using FIFO admission; kept separate from the original routing probe."
    if "routing-baseline" in parts:
        return "Synthetic pipeline versus available-replica follow-up; stronger routing comparator than cyclic routing."
    if "objective" in parts and experiment.startswith("objective-aware"):
        return "Latency versus throughput placement: stable/network conditions, concurrency 1/2, 32 output tokens."
    if "demand" in parts and experiment.startswith("objective-aware"):
        return "Fixed throughput versus auto-fixed/auto-remaining: stable conditions, concurrency 1/2, 64 output tokens."
    if "vm-single" in parts:
        return "Single-device baseline: all layers on vm2, one worker, three repeats, no injected fault."
    if "vm" in parts and experiment == "azure-vm-2026-10-04":
        return "Distributed real-model matrix: network/compute disturbances and worker loss, with policy comparisons."
    if "network" in parts:
        return "Network-delay arm of the historical kind benchmark; simulated inference with tc netem injection."
    if "worker-loss" in parts:
        return "Worker-loss arm of the historical kind benchmark; a stopped container represents the failure."
    if "phase1" in parts:
        return "Phase 1 analytical sensitivity sweep with hypothetical per-layer costs."
    if "phase4" in parts:
        return "Phase 4 analytical sensitivity sweep using measured CPU component inputs."
    if "analysis" in parts or "reports" in parts:
        return "Derived analysis or report; follow the linked study method and raw inputs."
    if "raw" in parts or "runs" in parts:
        return "Raw measured run artifacts; subfolders and meta.json identify the workload and conditions."
    return "Experiment artifacts and supporting material; see the study method for the evidence boundary."


def producer(experiment, relative, fallback):
    if experiment == "paper-ablations-2026-10-04":
        for segment, filename in (("queue-results", "queue_ablation.py"), ("calibration-results", "calibration.py")):
            if segment in Path(relative).parts:
                return f"docs/data/{experiment}/{filename}"
    if experiment == "azure-vm-2026-10-04" and "replay" in Path(relative).parts:
        return "cmd/gate-replay/main.go"
    return fallback


def describe(folder, experiment, relative):
    guide = folder / "README.md"
    if guide.is_symlink() or (guide.exists() and not guide.read_text().startswith(MARKER)):
        guide = folder / "EXPERIMENT.md"
    if guide.exists() and not guide.read_text().startswith(MARKER):
        raise RuntimeError(f"Refusing to replace existing guide: {guide}")
    meta_path = folder / "meta.json"
    meta = json.loads(meta_path.read_text()) if meta_path.exists() else None
    scope = role(experiment['id'], relative)
    heading = experiment['name']
    if meta:
        objective = meta.get('objective')
        arm = 'auto-remaining' if objective == 'auto' and meta.get('remaining_work_aware') else 'auto-fixed' if objective == 'auto' else objective
        heading += f" — {meta.get('scenario', 'unspecified')} / {arm or meta.get('policy', 'unspecified')} / repeat {meta.get('repeat', 'unspecified')}"
    text = [MARKER, f"# {heading}", "", "| Field | Details |", "|---|---|",
            f"| Experiment ID | `{experiment['id']}` |",
            f"| Experiment name | {experiment['name']} |",
            f"| Study date | {experiment['date']} |",
            f"| Environment | {experiment['environment']} |",
            f"| Evidence | {experiment['evidence']} |",
            f"| This folder | {scope} |",
            f"| Original source | {experiment['origin']} |",
            f"| Retained artifact path | `{folder.relative_to(ROOT)}` |",
            f"| Canonical collection | {link(folder, experiment['canonical_path'])} |",
            f"| Method / report | {link(folder, experiment['report'])} |"]
    source = producer(experiment['id'], relative, experiment['producer'])
    text.append(f"| Producing script | {link(folder, source)} |" if source else
                "| Producing script | Original profiling spike not retained as an executable; see the method report. |")
    if meta:
        text += ["", "## Recorded run settings", "",
                 f"Exact saved settings: {link(folder, meta_path, 'meta.json')}. "
                 "The script link identifies the producer; the saved metadata and source snapshots identify the tested version.", "",
                 "| Setting | Value |", "|---|---|"]
        keys = ['run', 'scenario', 'magnitude', 'policy', 'objective', 'remaining_work_aware',
                'workers', 'worker_device', 'concurrency', 'repeat', 'prompt_len', 'new_tokens',
                'context_len', 'kv_cache', 'link_source', 'cost_model', 'phases_s',
                'contaminated_by_unexpected_worker_restart']
        for key in keys:
            if key in meta:
                value = json.dumps(meta[key]) if isinstance(meta[key], (dict, list, bool)) else str(meta[key])
                text.append(f"| {key} | `{value.replace('|', '&#124;')}` |")
        if meta.get('t0'):
            start = datetime.fromtimestamp(meta['t0'], ZoneInfo('Asia/Calcutta'))
            text.append(f"| Measurement start | {start:%Y-%m-%d %H:%M:%S} IST |")
        if 'magnitude' in meta:
            text += ["", "Network magnitudes are injected delay in milliseconds; compute magnitudes are the CPU limit "
                     "passed to the fault script. Zero means no added magnitude for stable/loss scenarios. "
                     "Use faults.csv for the actual injection and clearance timestamps."]
    meanings = {'meta.json': 'Saved run conditions and initial state.',
                'requests.csv': 'Per-request successes/errors and token/timing measurements.',
                'series.csv': 'Sampled controller placement and telemetry over time.',
                'faults.csv': 'Fault injection, clearance and remote event times.',
                'decisions.json': 'Recorded candidate decisions, accept/reject reasons and executed changes.',
                'correctness.json': 'Fixed-input greedy tokens compared with the shared run reference.',
                'schedule.json': 'Planned conditions and repeat order.',
                'events.json': 'Matrix completion ledger and subprocess outcomes.',
                'provenance.json': 'Controller binary hash and recorded study identity.',
                'SOURCE_SHA256SUMS': 'Original VM file hashes; local folder guides are not VM outputs.',
                'SHA256SUMS': 'Integrity hashes of the collected local files.',
                'source-provenance.json': 'Recorded source/version information for the local probe.'}
    text += ["", "## Files and subfolders", "", "| Entry | Meaning |", "|---|---|"]
    for child in sorted(folder.iterdir()):
        if child.name in ('README.md', 'EXPERIMENT.md'):
            continue
        if child.is_dir():
            meaning = role(experiment['id'], str(Path(relative) / child.name))
        else:
            meaning = meanings.get(child.name, 'Process log.' if child.suffix == '.log' else
                                   'Figure.' if child.suffix in ('.png', '.svg', '.pdf') else
                                   'Saved source snapshot.' if child.suffix == '.tgz' else
                                   'Supporting artifact; see the method report.')
        text.append(f"| {link(folder, child, child.name)} | {meaning} |")
    text += ["", "This guide was generated locally from the experiment registry and saved metadata. "
             "It is documentation, not a new experiment or a source-VM measurement.", ""]
    guide.write_text('\n'.join(text))
    return guide


def main():
    experiments = json.loads((RESULTS / 'experiments.json').read_text())
    known = {e['id'] for e in experiments}
    unknown = {p.name for p in RESULTS.iterdir() if p.is_dir()} - known
    if unknown:
        raise RuntimeError(f"Add experiment provenance to results/experiments.json: {sorted(unknown)}")
    rows, seen = [], set()
    for experiment in experiments:
        locations = [RESULTS / experiment['id']]
        original = ROOT / 'docs/data' / experiment['id']
        if original.is_dir() and any(original.iterdir()):
            locations.append(original)
        for location in locations:
            for directory, _, _ in os.walk(location, followlinks=True):
                folder = Path(directory)
                physical = folder.resolve()
                if physical not in seen:
                    describe(physical, experiment, str(folder.relative_to(location)))
                    seen.add(physical)
                guide = folder / 'EXPERIMENT.md'
                if not guide.exists():
                    guide = folder / 'README.md'
                rows.append([experiment['id'], experiment['name'], str(folder.relative_to(ROOT)),
                             str(guide.relative_to(ROOT)), role(experiment['id'], str(folder.relative_to(location)))])
    with (RESULTS / 'folders.csv').open('w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['experiment_id', 'experiment_name', 'folder', 'guide', 'purpose'])
        w.writerows(rows)
    # Include new local documentation in the collection manifest without
    # changing any source-VM checksum manifest or measured artifact.
    study = RESULTS / 'objective-aware-2026-10-04'
    hashes = [f'{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.relative_to(study)}'
              for p in sorted(study.rglob('*')) if p.is_file() and p.name != 'SHA256SUMS']
    (study / 'SHA256SUMS').write_text('\n'.join(hashes) + '\n')
    print(f'Documented {len(seen)} physical folders; indexed {len(rows)} browsable folder paths.')


if __name__ == '__main__':
    main()
